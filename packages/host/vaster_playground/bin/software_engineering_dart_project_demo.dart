/// 2. Feature Implementation Component: Generates the core Dart library code.
class FeatureImplementationComponent extends ComposableNode {
  const FeatureImplementationComponent();

  @override
  VasterNode build(BuildContext context) {
    const devRole = AgentRole(
      roleId: 'software_engineer',
      name: 'Senior Dart Engineer',
      title: 'Core Engine Developer',
      instruction: 'Writes clean, safe, well-documented Dart code.',
    );

    return Agent(
      role: devRole,
      child: const Sequence([
        WriteFile(
          path: Template.text('/lib/calculator.dart'),
          content: Template.text('''
/// A high-performance calculator library generated by Vaster.
class Calculator {
  /// Adds two numbers together.
  double add(double a, double b) => a + b;

  /// Subtracts [b] from [a].
  double subtract(double a, double b) => a - b;

  /// Multiplies [a] by [b].
  double multiply(double a, double b) => a * b;

  /// Divides [a] by [b]. Throws [ArgumentError] if [b] is 0.
  double divide(double a, double b) {
    if (b == 0) {
      throw ArgumentError('Cannot divide by zero.');
    }
    return a / b;
  }
}
'''),
        ),
        WriteFile(
          path: Template.text('/bin/main.dart'),
          content: Template.text('''
import 'package:smart_calculator/calculator.dart';

void main() {
  final calc = Calculator();
  print('====================================================');
  print('  SMART CALCULATOR (GENERATED SOLELY BY VASTER)     ');
  print('====================================================');
  print('10 + 5 = \${calc.add(10, 5)}');
  print('10 - 5 = \${calc.subtract(10, 5)}');
  print('10 * 5 = \${calc.multiply(10, 5)}');
  print('10 / 5 = \${calc.divide(10, 5)}');
}
'''),
        ),
      ]),
    );
  }
}

/// 3. Unit Testing Component: Generates complete unit tests for the package.
class UnitTestingComponent extends ComposableNode {
  const UnitTestingComponent();

  @override
  VasterNode build(BuildContext context) {
    const qaRole = AgentRole(
      roleId: 'qa_engineer',
      name: 'QA Automation Engineer',
      title: 'Test Suite Lead',
      instruction: 'Writes rigorous unit tests.',
    );

    return Agent(
      role: qaRole,
      child: const WriteFile(
        path: Template.text('/test/calculator_test.dart'),
        content: Template.text('''
import 'package:smart_calculator/calculator.dart';
import 'package:test/test.dart';

void main() {
  group('Calculator Tests', () {
    late Calculator calc;

    setUp(() {
      calc = Calculator();
    });

    test('add adds numbers correctly', () {
      expect(calc.add(10, 5), equals(15));
    });

    test('subtract subtracts numbers correctly', () {
      expect(calc.subtract(10, 5), equals(5));
    });

    test('multiply multiplies numbers correctly', () {
      expect(calc.multiply(10, 5), equals(50));
    });

    test('divide divides numbers correctly', () {
      expect(calc.divide(10, 5), equals(2));
    });

    test('divide by zero throws ArgumentError', () {
      expect(() => calc.divide(10, 0), throwsArgumentError);
    });
  });
}
'''),
      ),
    );
  }
}

// ══════════════════════════════════════════════════════════════════════════════
// PIPELINE ASSEMBLY & DISK MOUNT EXECUTION
// ══════════════════════════════════════════════════════════════════════════════

void main() async {
  print('======================================================================');
  print('    VASTER REAL DISK DART PROJECT GENERATION PIPELINE                 ');
  print('  Software Engineering Composable Nodes → Real Local Filesystem       ');
  print('======================================================================\n');

  final outputDiskPath = '/tmp/vaster_dart_project';
  final diskDir = Directory(outputDiskPath);
  if (await diskDir.exists()) {
    await diskDir.delete(recursive: true);
  }
  await diskDir.create(recursive: true);

  print('📁 Real Target Disk Path: $outputDiskPath');

  // Assembly of Software Engineering Composable Nodes into root Pipeline
  const pipeline = Pipeline(
    spec: PipelineSpec(name: 'software_engineering_dart_project'),
    mounts: [StorageMount(mountPrefix: '/', diskPath: '/tmp/vaster_dart_project')],
    children: [
      DartProjectBootstrapComponent(projectName: 'smart_calculator'),
      FeatureImplementationComponent(),
      UnitTestingComponent(),
    ],
  );

  print('\n┌─ AST COMPILATION ──────────────────────────────────────────────┐');
  const compiler = BasicWorkflowCompiler();
  final program = compiler.compile(pipeline);
  print('  Pipeline Compiled: ${program.programName} (${program.instructions.length} instructions)');

  print('\n┌─ BOOTSTRAP VM WITH LOCAL DISK MOUNT ──────────────────────────┐');
  final liveModel = GeminiCliVasterModel(modelName: 'gemini-2.5-flash');

  final vm = await VasterVMEngine.bootstrap(
    config: VMConfig(defaultModel: liveModel, rootMountPath: outputDiskPath),
  );

  // Mount real local disk filesystem to VFS
  vm.mountFileSystem('/', LocalVasterFileSystem(outputDiskPath));
  print('  ✓ Real disk mount active: LocalVasterFileSystem → $outputDiskPath');

  print('\n┌─ EXECUTING PIPELINE SOLELY VIA VASTER VM ─────────────────────┐');
  final runtime = VasterRuntime(
    vm: vm,
    policy: ExecutionPolicy.unlimited,
    budget: ExecutionBudget(maxDuration: const Duration(minutes: 2)),
    scheduler: BasicVasterScheduler(taskQueue: PriorityTaskQueue()),
  );

  final state = await runtime.executeProgram(program);
  print('  ✓ Pipeline execution status: ${state.status.name}');
  await vm.shutdown();

  print('\n┌─ VERIFYING GENERATED DART PROJECT ON DISK ────────────────────┐');
  final generatedFiles = diskDir.listSync(recursive: true);
  print('  Generated files on real disk:');
  for (final entity in generatedFiles) {
    print('    • ${entity.path.replaceAll(outputDiskPath, '')}');
  }

  print('\n======================================================================');
  print('  SUCCESS! Dart project generated on real disk solely using Vaster!');
  print('======================================================================');
}
